import mt, mount_lib as M, objlist, sys
e=mt.new()
for tx in (48,64,80,96):
    M.mount(e,0xE)
    e.w16(0x512,tx); e.w16(0x516,48)
    e.run(1,p0=['RIGHT']); e.run(2,p2=['LEFT']); e.run(2,p2=['RIGHT'])
    q0=e.wram()[0x500:0x600]
    hit=None; shot=[]
    for f in range(120):
        e.run(1,p0=(['Y'] if f<3 else []), p2=['LEFT'] if f>=60 and f<90 else [])
        w=e.wram()
        o=[(o['x'],o['y'],hex(o['rt'])) for o in objlist.objs(e) if 0x800<=o['a']<0x1400 and (o['rt']>>8) in (0xC12D,0xC12E)]
        if o: shot.append((f,o[0]))
        if (w[0x5e4] or w[0x5e6]) and hit is None: hit=(f,w[0x5e4],w[0x5e6])
    q=e.wram()[0x500:0x600]
    print('alvo',tx,'hit',hit,'shot first/last',shot[:1],shot[-1:],'P3 x after LEFT 30f:',e.r16(0x512), 'diff', [(hex(i),q0[i],q[i]) for i in range(0x100) if q0[i]!=q[i] and i not in (0x12,0x13,0x26,0x27,0x30,0x31,0x34,0x35,0x88,0x89,0x8a,0x8b,0xd0,0x0c,0x0d,0x70,0x71,0x72,0x73,0x74,0x75,0x76,0x77,0x78,0x79,0x7a,0x7b,0x7c,0x7d,0x7e,0x7f,0x80,0x81,0x82,0x83,0x84)][:12])
